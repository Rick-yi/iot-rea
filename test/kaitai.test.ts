import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { diffFrames, type SchemaDraft } from '../src/app/diffFrames.js';
import { exportKsy, renderKaitai, sanitizeId } from '../src/app/exportKsy.js';
import { sensorObservations } from './helpers.js';

const cleanups: Array<() => Promise<void>> = [];
afterEach(async () => {
  for (const cleanup of cleanups.splice(0)) await cleanup();
});

async function draftFromSamples(): Promise<SchemaDraft> {
  const dir = await mkdtemp(path.join(tmpdir(), 'iot-rea-ksy-'));
  cleanups.push(() => rm(dir, { recursive: true, force: true }));
  const file = path.join(dir, 'obs.json');
  const observations = sensorObservations([21.5, 22.25, 23.0, 19.75, 24.5]);
  const payload = observations.map((obs) => ({
    frameId: obs.frameId,
    vars: obs.vars,
    hex: obs.bytes.toString('hex'),
  }));
  await writeFile(file, JSON.stringify(payload), 'utf8');
  return diffFrames({ path: file });
}

function fakeDraft(overrides: Partial<SchemaDraft>): SchemaDraft {
  return {
    sampleCount: 3,
    differential: {
      sampleCount: 3,
      lengths: [10, 10, 10],
      alignedLength: 10,
      regions: [],
      stableOffsets: [],
      unknowns: [],
      excludedFrameIds: [],
    },
    fields: [],
    checksums: [],
    unknowns: [],
    evidence: { source: { path: 'fixture', sha256: '0'.repeat(64), size: 0 } },
    ...overrides,
  };
}

describe('renderKaitai', () => {
  it('emits a sequential layout with explicit unknown gaps and inferred types', async () => {
    const rendered = renderKaitai(await draftFromSamples(), { id: 'Temp Sensor' });

    expect(rendered.id).toBe('temp_sensor');
    expect(rendered.text).toContain('meta:\n  id: temp_sensor');
    expect(rendered.text).toContain('- id: reserved_0\n    size: 4');
    expect(rendered.text).toContain('- id: temperature\n    type: f4le');
    expect(rendered.text).toContain('confidence 1.00');
    expect(rendered.text).toContain('- id: checksum_sum8\n    type: u1');
    expect(rendered.text).toContain('# unknown:');
  });

  it('drops a weaker overlapping hypothesis instead of emitting a broken seq', () => {
    const draft = fakeDraft({
      fields: [
        {
          offset: 4, width: 2, type: 'u16', endian: 'le', variable: 'weak',
          confidence: 0.6, matched: 3, total: 3, frameIds: [],
        },
        {
          offset: 4, width: 4, type: 'f32', endian: 'le', variable: 'temperature',
          confidence: 0.9, matched: 3, total: 3, frameIds: [],
        },
      ],
    });

    const rendered = renderKaitai(draft, { id: 'overlap' });

    expect(rendered.text).toContain('- id: temperature\n    type: f4le');
    expect(rendered.text).not.toContain('id: weak');
    expect(rendered.dropped[0]).toContain('overlaps a stronger field');
  });

  it('keeps checksum placement and its coverage in doc', () => {
    const draft = fakeDraft({
      differential: { ...fakeDraft({}).differential, alignedLength: 6 },
      checksums: [
        {
          algorithm: 'crc16-modbus', position: 4, width: 2, endian: 'le',
          coveredFrom: 0, coveredTo: 3, matched: 3, total: 3,
          confidence: 1, counterexamples: [],
        },
      ],
    });

    const rendered = renderKaitai(draft, { id: 'crc' });

    expect(rendered.text).toContain('- id: checksum_crc16_modbus\n    type: u2le');
    expect(rendered.text).toContain('over 0x0-0x3');
    expect(rendered.text).toContain('3/3 samples matched');
  });
});

describe('sanitizeId', () => {
  it('produces Kaitai-safe identifiers', () => {
    expect(sanitizeId('Temperature (C)')).toBe('temperature_c');
    expect(sanitizeId('---')).toBe('field');
    expect(sanitizeId('3-way')).toBe('f_3_way');
  });
});

describe('exportKsy', () => {
  it('writes the draft and reports its path', async () => {
    const draft = await draftFromSamples();
    const dir = await mkdtemp(path.join(tmpdir(), 'iot-rea-ksy-out-'));
    cleanups.push(() => rm(dir, { recursive: true, force: true }));
    const target = path.join(dir, 'frame.ksy');

    const written = await exportKsy(draft, target, { id: 'sensor' });

    expect(written.path).toBe(target);
    expect(written.text).toContain('id: sensor');
  });

  it('supports stdout mode without touching the filesystem', async () => {
    const rendered = await exportKsy(await draftFromSamples(), '-', { id: 'sensor' });
    expect(rendered.path).toBeNull();
    expect(rendered.text.startsWith('# Generated by iot-rea')).toBe(true);
  });
});
